from __future__ import annotations

from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

from app.module_catalog import ModuleEnvironment, engine_python
from app.module_evidence import capability_verified, environment_fingerprint, environment_verified, record_capability_success, VerificationReceipt


class ModuleEvidenceTests(unittest.TestCase):
    def test_import_bytecode_preserves_environment_receipt_without_polling_writes(self) -> None:
        for platform in ('linux', 'darwin', 'win32'):
            with self.subTest(platform=platform), tempfile.TemporaryDirectory() as temporary:
                environment = ModuleEnvironment.for_root(Path(temporary), platform=platform, architecture='arm64')
                engine = environment.paths['speech']
                (engine / 'GPT_SoVITS').mkdir(parents=True)
                (engine / 'api.py').write_text('# source')
                python = engine_python(engine, platform)
                python.parent.mkdir(parents=True)
                python.write_text('interpreter')
                site = engine / ('.venv/Lib/site-packages' if platform == 'win32' else '.venv/lib/python3.11/site-packages')
                package = site / 'openfabric_receipt_fixture'
                package.mkdir(parents=True)
                (package / '__init__.py').write_text('VALUE = 1\n')
                (site / 'receipt_module.py').write_text('VALUE = 2\n')
                fingerprint = environment_fingerprint(environment, 'speech')
                assert fingerprint is not None
                receipt = VerificationReceipt(root=str(engine.resolve()), fingerprint=fingerprint, environment_verified=True)
                receipt_path = environment.root / '.setup/verification/speech.json'
                receipt_path.parent.mkdir(parents=True)
                receipt_path.write_text(receipt.model_dump_json())
                self.assertTrue(environment_verified(environment, 'speech'))
                subprocess.run([sys.executable, '-c', 'import sys; sys.path.insert(0, sys.argv[1]); import openfabric_receipt_fixture; import receipt_module', str(site)], check=True, capture_output=True)
                self.assertTrue((package / '__pycache__').is_dir())
                self.assertTrue((site / '__pycache__').is_dir())
                (site / 'generated.pyc').write_bytes(b'generated bytecode')
                before_poll = {path: path.stat().st_mtime_ns for path in environment.root.rglob('*')}
                self.assertTrue(environment_verified(environment, 'speech'))
                self.assertEqual(before_poll, {path: path.stat().st_mtime_ns for path in environment.root.rglob('*')})
                (site / 'receipt_module.py').write_text('VALUE = 200\n')
                self.assertFalse(environment_verified(environment, 'speech'))

    def test_distribution_metadata_changes_invalidate_fingerprint(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            environment = ModuleEnvironment.for_root(Path(temporary), platform='linux', architecture='x64')
            engine = environment.paths['speech']
            (engine / 'GPT_SoVITS').mkdir(parents=True)
            (engine / 'api.py').write_text('# source')
            python = engine_python(engine, environment.platform)
            python.parent.mkdir(parents=True)
            python.write_text('interpreter')
            distribution = engine / '.venv/lib/python3.11/site-packages/torch-2.11.dist-info'
            distribution.mkdir(parents=True)
            for filename in ('METADATA', 'RECORD', 'INSTALLER', 'direct_url.json'):
                with self.subTest(filename=filename):
                    metadata = distribution / filename
                    metadata.write_text('before')
                    before = environment_fingerprint(environment, 'speech')
                    self.assertIsNotNone(before)
                    metadata.write_text('longer after')
                    self.assertNotEqual(before, environment_fingerprint(environment, 'speech'))

    def test_music_receipt_tracks_nested_inference_source_changes(self) -> None:
        from app.module_catalog import DEFINITIONS
        with tempfile.TemporaryDirectory() as temporary:
            environment = ModuleEnvironment.for_root(Path(temporary), platform='darwin', architecture='arm64')
            for identifier in ('stable_audio3',):
                engine = environment.paths[identifier]
                for marker in DEFINITIONS[identifier].source_markers:
                    path = engine / marker
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text('# source')
                python = engine_python(engine, environment.platform)
                python.parent.mkdir(parents=True)
                python.write_text('interpreter')
                (engine / '.venv/lib/python3.11/site-packages').mkdir(parents=True)
                root = engine / 'optimized/mlx'
                nested = root / 'nested.py'
                nested.write_text('# decoder before')
                record_capability_success(identifier, environment=environment, service_identity='local-test')
                self.assertTrue(capability_verified(environment, identifier, 'local-test'))
                nested.write_text('# decoder after')
                self.assertFalse(capability_verified(environment, identifier, 'local-test'))

    def test_ace_training_changes_invalidate_verification(self) -> None:
        from app.module_catalog import DEFINITIONS
        with tempfile.TemporaryDirectory() as temporary:
            environment = ModuleEnvironment.for_root(Path(temporary), platform='darwin', architecture='arm64')
            engine = environment.paths['ace_step']
            for marker in DEFINITIONS['ace_step'].source_markers:
                path = engine / marker
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text('# source')
            python = engine_python(engine, environment.platform)
            python.parent.mkdir(parents=True)
            python.write_text('interpreter')
            (engine / '.venv/lib/python3.12/site-packages').mkdir(parents=True)
            for relative in ('acestep/training/dataset_builder_modules/preprocess_audio.py',
                             'acestep/training/data_module.py', 'acestep/core/generation/handler/io_audio.py',
                             'acestep/training/trainer.py', 'acestep/core/generation/handler/service_generate_execute.py'):
                source = engine / relative
                source.parent.mkdir(parents=True, exist_ok=True)
                source.write_text('# audio reader before')
                fingerprint = environment_fingerprint(environment, 'ace_step')
                assert fingerprint is not None
                receipt = VerificationReceipt(root=str(engine.resolve()), fingerprint=fingerprint, environment_verified=True)
                marker = environment.root / '.setup/verification/ace_step.json'
                marker.parent.mkdir(parents=True, exist_ok=True)
                marker.write_text(receipt.model_dump_json())
                self.assertTrue(environment_verified(environment, 'ace_step'))
                source.write_text('# audio reader after')
                self.assertFalse(environment_verified(environment, 'ace_step'), relative)

    def test_receipt_is_bound_to_packages_checkout_and_service(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            environment = ModuleEnvironment.for_root(Path(temporary), platform='linux', architecture='x64')
            engine = environment.paths['speech']
            (engine / 'GPT_SoVITS').mkdir(parents=True)
            (engine / 'api.py').write_text('# source')
            python = engine_python(engine, environment.platform)
            python.parent.mkdir(parents=True)
            python.write_text('interpreter')
            site = engine / '.venv/lib/python3.11/site-packages'
            (site / 'torch-2.11.dist-info').mkdir(parents=True)
            (site / 'torch').mkdir()
            before = environment_fingerprint(environment, 'speech')
            record_capability_success('speech', environment=environment, service_identity='http://127.0.0.1:9880')
            self.assertTrue(capability_verified(environment, 'speech', 'http://127.0.0.1:9880'))
            self.assertFalse(capability_verified(environment, 'speech', 'http://127.0.0.1:9999'))
            (site / 'torch').rmdir()
            self.assertNotEqual(before, environment_fingerprint(environment, 'speech'))
            self.assertFalse(capability_verified(environment, 'speech', 'http://127.0.0.1:9880'))

    def test_status_fingerprinting_does_not_create_missing_directories(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            environment = ModuleEnvironment.for_root(root)
            self.assertIsNone(environment_fingerprint(environment, 'speech'))
            self.assertFalse(capability_verified(environment, 'speech', 'http://127.0.0.1:9880'))
            self.assertEqual(list(root.iterdir()), [])
